import { chromium } from 'playwright';
const exe = process.env.HOME + '/Library/Caches/ms-playwright/chromium_headless_shell-1243/chrome-headless-shell-mac-arm64/chrome-headless-shell';
const b = await chromium.launch({ executablePath: exe });
const p = await (await b.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
p.on('console', m => { if (['error','warning'].includes(m.type())) console.log('CONSOLE', m.type(), m.text().slice(0, 300)); });
p.on('pageerror', e => console.log('PAGEERROR', String(e.stack||e).slice(0, 800)));
p.on('response', r => { const u = r.url(); if (u.includes('/functions/v1/') ) console.log('FN', r.status(), u.split('/functions/v1/')[1]); });
await p.goto('https://time-2-read.com/', { waitUntil: 'networkidle' });
await p.getByText('Only needed').click().catch(()=>{});
await p.getByText('Create Your First Story').first().click();
await p.waitForTimeout(2000);
await p.locator('input').first().fill('Maya');
await p.getByText('Skip and create story now').click();
await p.waitForTimeout(25000);
console.log('URL', p.url());
await p.getByText('Start Adventure').click().catch(()=>{});
await p.waitForTimeout(15000);
console.log('URL2', p.url(), (await p.locator('body').innerText()).replace(/\s+/g,' ').slice(0,200));
await b.close();
